    consumospa,
    tomacitologia,
    mamografia,
    remisionespecifica,
    discapacidad,
    canalizacionuno ,
    canalizaciondos ,
    canalizaciontres ,
    'Infante' as cursodevida FROM agsolutic_aps2024.infantils
    UNION ALL
    SELECT 
    numerodoc AS doc_id ,
    familia_id, 
    tipodocumento , 
    primerapellido , 
    segundoapellido , 
    primernombre , 
    segundonombre,
    gestacion ,
    condicioncronica,
    esquemavacunacion,
    desparasitacion ,
    valoracionmedica as valoracion,
    saludoral as higiene_oral,
    aseguradora ,
    regimen ,
    metodosanticonceptivos,
    infeccionestransmisionsexual,
    controlprenatal as controlP,
    consumospa,
    tomacitologia,
    mamografia,
    remisionespecifica,
    discapacidad,
    canalizacionuno ,
    canalizaciondos ,
    canalizaciontres ,
    'PrimeraInfancia' as cursodevida FROM agsolutic_aps2024.primerainfancias
    UNION ALL
    SELECT     
    numerodoc AS doc_id ,
    familia_id, 
    tipodocumento , 
    primerapellido , 
    segundoapellido , 
    primernombre , 
    segundonombre,
    gestacion ,
    condicioncronica,
    esquemavacunacion,
    desparasitacion ,
    valoracionmedica as valoracion,
    saludoral as higiene_oral,
    aseguradora ,
    regimen ,
    metodosanticonceptivos,
    infeccionestransmisionsexual,
